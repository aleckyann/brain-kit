// Sixty messages of a thousand characters on one day: more than one digest
// holds, so the day is cut from its start and its end is kept.
function longDay(world, name = 'long.jsonl', count = 60, size = 996) {
  const messages = [];
  for (let i = 0; i < count; i += 1) messages.push(user(`m${String(i).padStart(2, '0')} ${'w'.repeat(size)}`, MINUTE(i)));
  return world.write(PROJECT, name, messages);
}

for (const [lang, cut] of [
  ['en', (n, c) => `cut: the first ${n} messages and ${c} characters were left out`],
  ['pt-BR', (n, c) => `corte: as primeiras ${n} mensagens e ${c} caracteres ficaram de fora`],
]) {
  test(`${lang}: a lone day that holds more than a digest can carry keeps its END, and the header and the block both say what was cut`, () => {
    const world = makeWorld({ lang });
    const file = longDay(world);
    const plan = world.collect();
    const { digest } = plan.files[0];
    assert.ok(digest.kept > 10 && digest.kept < 60, JSON.stringify(digest));
    assert.equal(digest.held, 60);
    assert.equal(digest.cutMessages, 60 - digest.kept);
    assert.equal(digest.cutChars, digest.cutMessages * 1000);
    const lines = linesOf(digestText(plan, file));
    assert.ok(lines[0].endsWith(`${cut(digest.cutMessages, digest.cutChars)}.`), lines[0]);
    assert.ok(lines[1].includes(`] m${String(digest.cutMessages).padStart(2, '0')} `), 'the oldest kept is the first after the cut');
    assert.ok(lines.at(-1).includes('] m59 '), 'the newest is kept');
    const fileLine = plan.promptBlock.split('\n').find((l) => l.includes(digestOf(plan, file)));
    assert.ok(fileLine.endsWith(`; ${cut(digest.cutMessages, digest.cutChars)})`), fileLine);
    assert.deepEqual(plan.daysCovered, ['2026-09-23'], 'the one day still closes');
  });
}

// The smallest number of equal messages for which the digest leaves out
// exactly one.
function cutByOne(world) {
  for (let count = 2; count < 40; count += 1) {
    const file = longDay(world, `one-${count}.jsonl`, count, 1796);
    const plan = world.collect();
    const digest = plan.files.find((f) => f.path === file).digest;
    if (digest.cutMessages === 1) return { file, plan, digest };
    rmSync(file);
  }
  throw new Error('no count leaves out exactly one message');
}

test('a cut of exactly one message is said too, in the header and in the block', () => {
  const world = makeWorld();
  const { file, plan, digest } = cutByOne(world);
  assert.equal(digest.cutMessages, 1);
  assert.match(linesOf(digestText(plan, file))[0], /this digest keeps the last \d+; cut: the first 1 messages and 1800 characters were left out\.$/);
  const fileLine = plan.promptBlock.split('\n').find((l) => l.includes(digestOf(plan, file)));
  assert.match(fileLine, /; cut: the first 1 messages and 1800 characters were left out\)$/);
});

// The review's 3-day case (fix round 1, Important 3): one session with
// twelve messages of about 1 700 characters on each of 21, 22 and
// 23/09/2026. One day fits a digest whole, two do not: 21/09 is offered
// whole and 22 and 23/09 stay open, never cut away.
const THREE_DAYS = { from: new Date('2026-09-21T03:00:00.000Z'), to: new Date('2026-09-24T03:00:00.000Z'), timezone: TIMEZONE, days: ['2026-09-21', '2026-09-22', '2026-09-23'] };

function threeDays(world, name = 'dddddddd-1111-4222-8333-444444444444.jsonl', perDay = 12) {
  const lines = [];
  for (const [day, tag] of [['2026-09-21', 'DAY21'], ['2026-09-22', 'DAY22'], ['2026-09-23', 'DAY23']]) {
    for (let i = 0; i < perDay; i += 1) {
      const at = new Date(Date.parse(`${day}T12:00:00.000Z`) + i * 60_000).toISOString();
      lines.push(i % 2 ? assistant(`${tag} reply ${i} ${'x'.repeat(1700)}`, at) : user(`${tag} Ana said ${i} ${'y'.repeat(1700)}`, at));
    }
  }
  return world.write(PROJECT, name, lines);
}

for (const [lang, note, block] of [
  ['en', 'The days 22/09/2026, 23/09/2026 stay open for a later round: this round\'s digests could not hold them whole after the days before them.', /^The days 22\/09\/2026, 23\/09\/2026 wait for a later round: the digest of session dddddddd could not hold them whole after the days before them, and a digest must stay readable whole \(under 24000 bytes as Read prints it\)\. Only whole days are offered; 1 transcripts with messages only on those days wait with them\.$/],
  ['pt-BR', 'Os dias 22/09/2026, 23/09/2026 ficam abertos para uma próxima rodada: os extratos desta rodada não conseguiram guardá-los inteiros depois dos dias anteriores.', /^Os dias 22\/09\/2026, 23\/09\/2026 ficam para uma próxima rodada: o extrato da sessão dddddddd não conseguiu guardá-los inteiros/],
]) {
  test(`${lang}: a digest that cannot hold every day of the window offers whole days, oldest first, and leaves the others open, said in the header and the block`, () => {
    const world = makeWorld({ lang });
    const file = threeDays(world);
    world.write(PROJECT, 'eeeeeeee-1111-4222-8333-444444444444.jsonl', [user('only on the last day', '2026-09-23T15:00:00.000Z')]);
    const plan = transcriptsSource.collect({ window: THREE_DAYS, config: world.config, machine: world.machine, now: NOW, digestDir: world.digestDir });
    assert.deepEqual(plan.daysCovered, ['2026-09-21']);
    assert.deepEqual(plan.daysDeferred, ['2026-09-22', '2026-09-23']);
    assert.deepEqual(plan.digestDeferred, ['2026-09-22', '2026-09-23']);
    assert.deepEqual(plan.digestLimitedBy, ['dddddddd']);
    assert.equal(plan.window.to, '2026-09-22T03:00:00.000Z', 'the window, and so the mark, end at the last day offered whole');
    assert.deepEqual(plan.files.map((f) => f.path), [file], 'a session with nothing on the covered day waits');
    assert.equal(plan.dropped.byDigest, 1);
    assert.equal(plan.files[0].lastAt.slice(0, 10), '2026-09-21');
    const text = digestText(plan, file);
    assert.equal((text.match(/\] DAY21 /g) ?? []).length, 12, 'the day offered is offered whole');
    assert.doesNotMatch(text, /DAY22|DAY23/, 'the days left are not in it, not even in part');
    assert.equal(plan.files[0].digest.cutMessages, 0);
    assert.ok(linesOf(text)[0].endsWith(note), linesOf(text)[0]);
    assert.ok(plan.promptBlock.split('\n').some((line) => block.test(line)), plan.promptBlock);
    assert.ok(printedBytes(text) < DIGEST_LIMITS.readBytes);
  });
}

