test('a digest covers only the days the plan covers: a message on a day the cap defers belongs to a later round', () => {
  const world = makeWorld({ cap: 1 });
  const both = world.write(PROJECT, 'both.jsonl', [user('on the first day', AT('10:00')), user('on the deferred day', '2026-09-24T10:00:00.000Z')]);
  world.write(PROJECT, 'later.jsonl', [user('only on the deferred day', '2026-09-24T11:00:00.000Z')]);
  const window = { from: FROM, to: new Date(TO.getTime() + 24 * 3600 * 1000), timezone: TIMEZONE };
  const plan = transcriptsSource.collect({ window, config: world.config, machine: world.machine, now: NOW, digestDir: world.digestDir });
  assert.deepEqual(plan.daysCovered, ['2026-09-23']);
  assert.deepEqual(plan.files.map((f) => f.path), [both]);
  assert.deepEqual(linesOf(digestText(plan, both)).slice(1), ['[07:00 user] on the first day'], 'one day covered: no date in front, and nothing of the deferred day');
});

