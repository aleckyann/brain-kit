// The bound (ruling R-D1 of fix round 1): what Read prints for a digest,
// its numbers included, stays under DIGEST_LIMITS.readBytes UTF-8 bytes,
// and every token covers at least one byte, so it is under Read's 25 000
// tokens whatever the script. Each case fills one day with far more than a
// digest holds, of the script that costs the most bytes per character, or
// the most lines: the digest is cut, and what Read prints is still under
// the bound, and accepted whole.
const LONG_PROJECT = `-home-ana-${'p'.repeat(245)}`;
const SCRIPTS = [
  ['Chinese', () => '漢'.repeat(DIGEST_LIMITS.messageChars)],
  ['emoji', () => '\u{1F600}'.repeat(DIGEST_LIMITS.messageChars / 2)],
  ['base64', (i) => Buffer.from(Array.from({ length: 1350 }, (_, k) => (i * 31 + k * 7) % 256)).toString('base64')],
  ['Portuguese', () => 'ação de revisão com acentuação '.repeat(58)],
  ['many short lines', () => 'ok'],
];

for (const lang of ['en', 'pt-BR']) {
  test(`${lang}: whatever the script, what Read prints for a digest stays under 24 000 bytes, so under 25 000 tokens, and is read whole`, () => {
    const world = makeWorld({ lang, include: [LONG_PROJECT] });
    const files = SCRIPTS.map(([name, text]) => {
      const count = name === 'many short lines' ? 3000 : 200;
      const lines = [];
      for (let i = 0; i < count; i += 1) lines.push(assistant(text(i), new Date(FROM.getTime() + i * 20_000).toISOString()));
      return [name, world.write(LONG_PROJECT, `${name.replace(/ /g, '-')}.jsonl`, lines)];
    });
    const plan = world.collect();
    writeDigests(plan);
    for (const [name, file] of files) {
      const path = digestOf(plan, file);
      const text = readFileSync(path, 'utf8');
      const lines = linesOf(text);
      const printed = printedBytes(text);
      assert.ok(printed < DIGEST_LIMITS.readBytes, `${name}: Read prints ${printed} bytes`);
      assert.ok(printed > 20_000, `${name}: the budget is used (${printed} bytes)`);
      assert.ok(printed <= READ_MAX_TOKENS, `${name}: at most ${READ_MAX_TOKENS} tokens`);
      assert.ok(statSync(path).size < READ_MAX_BYTES);
      assert.ok(lines.length < READ_DEFAULT_LINES, `${name}: ${lines.length} lines`);
      assert.ok(lines.every((line) => line.length < 2000), `${name}: no line Read would cut`);
      // The kit's own reckoning of a line (its bytes, its newline, 12 for
      // Read's number) never counts less than what Read prints.
      const reckoned = lines.reduce((sum, line) => sum + Buffer.byteLength(line) + 1 + DIGEST_LIMITS.lineBytes, 0);
      assert.ok(reckoned >= Buffer.byteLength(numbered(lines)), name);
      assert.ok(reckoned < DIGEST_LIMITS.readBytes, `${name}: reckoned ${reckoned}`);
      const read = emulateRead({ file_path: path });
      assert.equal(read.isError, false, `${name}: ${read.content.slice(0, 200)}`);
      assert.ok(plan.files.find((f) => f.path === file).digest.cutMessages > 0, `${name}: cut, and said`);
    }
    const header = linesOf(readFileSync(digestOf(plan, files[0][1]), 'utf8'))[0];
    assert.ok(header.length < 1000, `the longest header (${header.length} characters, a 255-character project)`);
  });
}

