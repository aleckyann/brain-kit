test('writeDigests writes each digest owner-only (0600) in a folder of its own (0700), never over a file already there, and nothing for a plan with none', () => {
  const world = makeWorld();
  world.write(PROJECT, 'a.jsonl', [user('Ana asks', AT('10:00'))]);
  world.write(PROJECT, 'b.jsonl', [user('Ana asks again', AT('11:00'))]);
  const plan = world.collect();
  const old = process.umask(0o000);
  try {
    assert.equal(writeDigests(plan), 2);
  } finally {
    process.umask(old);
  }
  assert.equal(statSync(world.digestDir).mode & 0o777, 0o700);
  assert.equal(statSync(dirname(world.digestDir)).mode & 0o777, 0o700);
  for (const file of plan.files) {
    assert.equal(statSync(file.digest.path).mode & 0o777, 0o600);
    assert.equal(readFileSync(file.digest.path, 'utf8'), plan.digestTexts.find((d) => d.path === file.digest.path).text);
  }
  assert.throws(() => writeDigests(plan), /EEXIST/, 'a second write never replaces a digest');
  assert.equal(JSON.stringify(plan).includes('Ana asks'), false, 'no JSON copy of the plan carries a digest\'s text');
  assert.equal(writeDigests({ files: [] }), 0);
  const bare = transcriptsSource.collect({ window: { from: FROM, to: TO }, config: world.config, machine: world.machine, now: NOW });
  assert.equal(writeDigests(bare), 0);
  rmSync(world.digestDir, { recursive: true });
});

test('a transcript that cannot be read again for its digest leaves the offer for the unreadable list: its day stays open', () => {
  const world = makeWorld();
  const fine = world.write(PROJECT, 'fine.jsonl', [user('Ana asks', AT('10:00'))]);
  const flaky = world.write(PROJECT, 'flaky.jsonl', [user('Ana asks again', AT('11:00'))]);
  let opens = 0;
  const io = {
    openSync: (path, flags) => {
      if (path === flaky && (opens += 1) > 1) throw Object.assign(new Error('EIO: i/o error'), { code: 'EIO' });
      return openSync(path, flags);
    },
    readSync,
    closeSync,
  };
  const plan = transcriptsSource.collect({ window: { from: FROM, to: TO }, config: world.config, machine: world.machine, now: NOW, digestDir: world.digestDir, io });
  assert.deepEqual(plan.files.map((f) => f.path), [fine]);
  assert.deepEqual(plan.unreadable, [{ path: flaky, project: PROJECT, bytes: statSync(flaky).size }]);
  assert.equal(plan.dropped.unreadable, 1);
  assert.deepEqual(plan.digestTexts.map((d) => d.path), [digestOf(plan, fine)]);
  assert.deepEqual(transcriptsSource.readEvidence({ toolUses: [{ id: 'u', name: 'Read', input: { file_path: digestOf(plan, fine) } }], toolResults: [{ toolUseId: 'u', isError: false }] }, plan), { read: 1, expected: 2, ok: false });
});

test('every message key of the digest renders in both packs with nothing left over', () => {
  for (const lang of ['en', 'pt-BR']) {
    const t = createTranslator(lang);
    const cut = t('sources.transcripts.digest_cut', { messages: 3, chars: 120 });
    const header = t('sources.transcripts.digest_header_cut', { session: 's', project: 'p', from: 'a', to: 'b', timezone: 'UTC', held: 9, kept: 6, cut });
    assert.doesNotMatch(header, /\{[a-z]+\}/, lang);
    assert.ok(header.includes(cut), lang);
  }
});
