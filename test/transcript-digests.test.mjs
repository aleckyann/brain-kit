// The digest of a transcript (src/sources/transcripts-claude-code.mjs):
// what the model reads in place of each kept transcript since 01/10/2026,
// when the first real round on a real vault found transcripts the Read
// tool refuses (docs/incidents.md). What it holds (only the person's and
// the assistant's own text inside the window, in order of time), what it
// never holds (tool calls, tool results, thinking, what the harness writes
// into a user message), how it is bounded (under 24 000 bytes as Read
// prints it, whole days only, a lone day too big cut from its end, every
// cut and every day left said in the vault's language), and the proof that
// any digest is one Read whole, whatever its script. Every transcript here
// is built by hand (test/helpers/transcripts-world.mjs) from the shapes the
// review of fix round 1 listed; no test reads a real one.
